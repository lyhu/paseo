// Markdown portability and stable-key patch adapted from paseo-advanced-markdown
// (Apache-2.0), scripts/build.mjs by custyhs:
// https://github.com/custyhs/paseo-advanced-markdown
// The stable-key patch originates in Paseo (Apache-2.0), commit c43df5d4.
// Changes: bundle only the Markdown engine, emit third-party licenses, and omit
// the math/Mermaid extensions and their server dependencies.
import { build } from "esbuild";
import { transformAsync } from "@babel/core";
import transformClasses from "@babel/plugin-transform-classes";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const markdownRoot = path.dirname(require.resolve("react-native-markdown-display/package.json"));
const output = path.join(root, "client/generated/markdown.gen.ts");
await mkdir(path.dirname(output), { recursive: true });

function replaceExact(source, before, after) {
  if (!source.includes(before))
    throw new Error("Pinned Markdown source changed; review stable-key patch");
  return source.replace(before, after);
}

const result = await build({
  stdin: {
    contents:
      'export { default } from "react-native-markdown-display"; export { default as MarkdownIt } from "markdown-it";',
    resolveDir: root,
    loader: "ts",
  },
  outfile: output,
  bundle: true,
  format: "esm",
  platform: "neutral",
  mainFields: ["module", "main"],
  alias: {
    "markdown-it": path.dirname(require.resolve("markdown-it/package.json")),
    "react-native-fit-image": path.join(root, "client/fit-image.tsx"),
  },
  target: "es2020",
  define: { "process.env.NODE_ENV": '"production"' },
  jsx: "automatic",
  loader: { ".js": "jsx" },
  external: ["react", "react/jsx-runtime", "react-native"],
  legalComments: "eof",
  metafile: true,
  plugins: [
    {
      name: "stable-markdown-keys",
      setup(context) {
        context.onLoad(
          { filter: /(?:AstRenderer|tokensToAST)\.js$/ },
          async ({ path: filename }) => {
            if (!filename.startsWith(markdownRoot + path.sep)) return;
            let source = await readFile(filename, "utf8");
            if (filename.endsWith("AstRenderer.js")) {
              source = replaceExact(source, "import getUniqueID from './util/getUniqueID';", "");
              source = replaceExact(source, "key: getUniqueID(),", "key: 'rnmr_root',");
            } else {
              source = replaceExact(source, "import getUniqueID from './getUniqueID';", "");
              source = replaceExact(
                source,
                "function createNode(token, tokenIndex)",
                "function createNode(token, tokenIndex, parentKey)",
              );
              source = replaceExact(
                source,
                "const content = token.content;",
                "const content = token.content;\n  const keyPath = parentKey ? `${parentKey}.${tokenIndex}` : `${tokenIndex}`;",
              );
              source = replaceExact(
                source,
                "key: getUniqueID() + '_' + type,",
                "key: `rnmr_${keyPath}_${type}`,",
              );
              source = replaceExact(
                source,
                "children: tokensToAST(token.children)",
                "children: tokensToAST(token.children, keyPath)",
              );
              source = replaceExact(
                source,
                "function tokensToAST(tokens)",
                "function tokensToAST(tokens, parentKey = '')",
              );
              source = replaceExact(
                source,
                "createNode(token, i)",
                "createNode(token, i, parentKey)",
              );
            }
            return { contents: source, loader: "jsx" };
          },
        );
      },
    },
  ],
});

const lowered = await transformAsync(await readFile(output, "utf8"), {
  filename: output,
  babelrc: false,
  configFile: false,
  plugins: [transformClasses],
});
if (!lowered?.code) throw new Error("Markdown class lowering produced no code");
await writeFile(
  output,
  `// @ts-nocheck\n/* eslint-disable */\n/* Generated by scripts/build-markdown.mjs; see markdown.LICENSES.txt. */\n${lowered.code}\n`,
);
await writeFile(
  path.join(root, "client/generated/markdown-types.d.ts"),
  "/* eslint-disable */\n/* Generated dependency declarations; see markdown.LICENSES.txt. */\n" +
    replaceExact(
      await readFile(path.join(markdownRoot, "src/index.d.ts"), "utf8"),
      "import Token from 'markdown-it/lib/token';",
      "import type Token from 'markdown-it/lib/token.mjs';",
    ),
);

const packages = new Map();
for (const filename of Object.keys(result.metafile.inputs)) {
  const match = path.resolve(filename).match(/^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\//);
  if (match) packages.set(match[2], match[1]);
}
const licenses = [];
for (const [name, directory] of packages) {
  const pkg = JSON.parse(await readFile(path.join(directory, "package.json"), "utf8"));
  let license;
  for (const filename of [
    "LICENSE",
    "LICENSE.md",
    "LICENSE.txt",
    "LICENSE-MIT.txt",
    "license",
    "license.md",
  ]) {
    try {
      license = await readFile(path.join(directory, filename), "utf8");
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  if (!license) throw new Error(`Missing bundled license for ${name}`);
  licenses.push(`${name}@${pkg.version} (${pkg.license})\n${license}`);
}
licenses.push(
  `Stable-key and portability adaptation: Paseo and paseo-advanced-markdown, Apache-2.0.\n${await readFile(path.join(root, "scripts/APACHE-2.0.txt"), "utf8")}`,
);
await writeFile(
  path.join(root, "client/generated/markdown.LICENSES.txt"),
  licenses.join("\n\n---\n\n"),
);
console.log(`Built portable Markdown engine (${packages.size} bundled packages).`);
